// Demo-mode code generator. Produces a small, readable scaffold from the diagram in the browser.
// The real backend (blueprint_core generators) replaces this and emits full projects.
import { pascal, slug, snake } from "../names";
import type { Diagram, DiagramEdge, DiagramNode } from "../types";
import type { ZipFile } from "./zip";

type Field = { name: string; type: string; required?: boolean; target?: string };
const str = (v: unknown): string => (typeof v === "string" ? v : v === null || v === undefined ? "" : String(v));
const lit = (v: unknown): string => JSON.stringify(str(v));

const tables = (d: Diagram) =>
  d.nodes
    .filter((n) => n.type === "entity")
    .map((n) => ({
      name: pascal(str(n.config["name"])),
      fields: (Array.isArray(n.config["fields"]) ? (n.config["fields"] as Field[]) : []).map((f) => ({
        ...f,
        name: snake(str(f.name)),
      })),
    }));

const outgoing = (d: Diagram, id: string): DiagramEdge[] => d.edges.filter((e) => e.source === id);

type Lang = "py" | "js";

/** One flow = the steps after an event, rendered as indented code lines. */
function renderSteps(d: Diagram, fromId: string, lang: Lang, depth: number, branch?: string | null): string[] {
  const unit = lang === "py" ? "    " : "  ";
  const pad = unit.repeat(depth);
  const out: string[] = [];
  const nodes = new Map(d.nodes.map((n) => [n.id, n]));
  const ctx = (k: string) => (lang === "py" ? `ctx.get(${lit(snake(k))})` : `ctx[${lit(snake(k))}]`);
  const set = (k: string, v: string) => (lang === "py" ? `ctx[${lit(k)}] = ${v}` : `ctx[${lit(k)}] = ${v};`);
  const call = (fn: string, args: string) => (lang === "py" ? `${fn}(${args})` : `await ${fn}(${args});`);
  const note = (s: string) => `${lang === "py" ? "#" : "//"} ${s}`;

  const edges = outgoing(d, fromId).filter((e) => (branch === undefined ? true : e.source_handle === branch));
  for (const e of edges) {
    const n: DiagramNode | undefined = nodes.get(e.target);
    if (!n) continue;
    out.push(`${pad}${note(`block ${n.id}`)}`);
    switch (n.type) {
      case "set_field":
        out.push(`${pad}${set(snake(str(n.config["field"])), lit(n.config["value"]))}`);
        break;
      case "update_status":
        out.push(`${pad}${set("status", lit(n.config["status"]))}`);
        break;
      case "send_sms":
        out.push(`${pad}${call("integrations.send_sms", `${ctx(str(n.config["to_field"]))}, render(${lit(n.config["message"])}, ctx)`)}`);
        break;
      case "send_email":
        out.push(`${pad}${call("integrations.send_email", `${ctx(str(n.config["to_field"]))}, ${lit(n.config["subject"])}, render(${lit(n.config["message"])}, ctx)`)}`);
        break;
      case "charge_payment":
        out.push(`${pad}${call("integrations.charge_payment", `${lit(n.config["provider"])}, ${ctx(str(n.config["amount_field"]))}`)}`);
        break;
      case "custom_code":
        out.push(`${pad}${note(str(n.config["description"]).replace(/\s+/g, " "))}`);
        out.push(`${pad}${call("integrations.custom_code", `${lit(n.id)}, ctx`)}`);
        break;
      case "sql_query":
        out.push(`${pad}ctx[${lit(str(n.config["result_key"]))}] = ${lang === "py" ? "" : "await "}integrations.run_query(${lit(str(n.config["sql"]))}, ctx)${lang === "py" ? "" : ";"}`);
        break;
      case "condition": {
        const op = lit(n.config["operator"]);
        const test = `compare(${ctx(str(n.config["field"]))}, ${op}, ${lit(n.config["value"])})`;
        out.push(lang === "py" ? `${pad}if ${test}:` : `${pad}if (${test}) {`);
        const yes = renderSteps(d, n.id, lang, depth + 1, "true");
        out.push(...(yes.length ? yes : [`${pad}${unit}${lang === "py" ? "pass" : "// nothing"}`]));
        const no = renderSteps(d, n.id, lang, depth + 1, "false");
        if (no.length) {
          out.push(lang === "py" ? `${pad}else:` : `${pad}} else {`);
          out.push(...no);
        }
        if (lang === "js") out.push(`${pad}}`);
        continue; // a condition's children were rendered above
      }
      default:
        out.push(`${pad}${note(`${n.type} (no code needed)`)}`);
    }
    out.push(...renderSteps(d, n.id, lang, depth, null));
  }
  return out;
}

const events = (d: Diagram) =>
  d.nodes
    .filter((n) => n.type === "event")
    .map((n) => ({ node: n, name: snake(str(n.config["name"])), entity: pascal(str(n.config["entity"])) }));

const sqlType = (t: string): string =>
  ({ string: "VARCHAR(255)", text: "TEXT", integer: "INTEGER", number: "NUMERIC", boolean: "BOOLEAN", date: "DATE", datetime: "TIMESTAMP", foreign_key: "INTEGER" })[t] ?? "TEXT";

const README = (d: Diagram, target: string, ai: boolean, run: string): string => `# ${d.name}

Generated by Blueprint (**demo mode**: built in your browser as a starter scaffold, not by the Blueprint backend).
Target: \`${target}\`${ai ? " (AI-assisted mode needs the real backend, so this is the plain scaffold)" : ""}.

## Run
${run}

## What is in here
- ${tables(d).length} table(s): ${tables(d).map((t) => t.name).join(", ") || "none"}
- ${events(d).length} event flow(s): ${events(d).map((e) => e.name).join(", ") || "none"}
- \`integrations\` is yours: SMS, email, payment and custom code are stubs that only print.
`;

const PY_HELPERS = `def render(template, ctx):
    class _D(dict):
        def __missing__(self, key):
            return ""
    return template.format_map(_D(ctx))


def compare(actual, op, expected):
    if op == "contains":
        return str(expected).lower() in str(actual).lower()
    try:
        if isinstance(actual, (int, float)):
            expected = float(expected)
    except ValueError:
        return False
    ops = {"eq": lambda a, b: a == b, "ne": lambda a, b: a != b, "gt": lambda a, b: a > b,
           "gte": lambda a, b: a >= b, "lt": lambda a, b: a < b, "lte": lambda a, b: a <= b}
    return ops[op](actual, expected) if actual is not None else False
`;

const PY_INTEGRATIONS = `"""Yours to edit. Blueprint will not overwrite this file."""


def send_sms(to, message):
    print(f"[sms] {to}: {message}")


def send_email(to, subject, message):
    print(f"[email] {to} | {subject}: {message}")


def charge_payment(provider, amount):
    print(f"[payment] {provider}: {amount}")


def custom_code(block_id, ctx):
    print(f"[custom] {block_id} not implemented yet")


def run_query(sql, ctx):
    print(f"[sql] {sql}")
    return []
`;

function flowsPy(d: Diagram): string {
  const fns = events(d).map((e) => {
    const body = renderSteps(d, e.node.id, "py", 1, undefined);
    return `def ${e.name}(ctx):\n${(body.length ? body : ["    pass"]).join("\n")}\n    return ctx\n`;
  });
  const registry = events(d).map((e) => `    ${lit(e.name)}: ${e.name},`).join("\n");
  return `from . import integrations\n\n\n${PY_HELPERS}\n\n${fns.join("\n\n")}\n\nFLOWS = {\n${registry}\n}\n`;
}

function fastapi(d: Diagram, ai: boolean): ZipFile[] {
  const models = tables(d)
    .map((t) => {
      const cols = t.fields
        .filter((f) => f.type !== "many_to_many")
        .map((f) => {
          const col = f.type === "foreign_key" ? `Integer, ForeignKey("${snake(str(f.target))}s.id")` : { string: "String", text: "Text", integer: "Integer", number: "Float", boolean: "Boolean", date: "Date", datetime: "DateTime" }[f.type] ?? "String";
          return `    ${f.name} = Column(${col}, nullable=${f.required ? "False" : "True"})`;
        });
      return `class ${t.name}(Base):\n    __tablename__ = "${snake(t.name)}s"\n    id = Column(Integer, primary_key=True)\n${cols.join("\n")}\n`;
    })
    .join("\n\n");
  const routes = tables(d)
    .map((t) => `@app.get("/${snake(t.name)}s")\ndef list_${snake(t.name)}s():\n    return {"table": "${t.name}", "items": []}  # TODO: query the database\n`)
    .join("\n");
  return [
    { path: "README.md", content: README(d, "fastapi", ai, "```sh\npip install -r requirements.txt\nuvicorn app.main:app --reload\n```") },
    { path: "requirements.txt", content: "fastapi\nuvicorn\nsqlalchemy\npsycopg[binary]\n" },
    { path: "app/__init__.py", content: "" },
    { path: "app/models.py", content: `from sqlalchemy import Boolean, Column, Date, DateTime, Float, ForeignKey, Integer, String, Text\nfrom sqlalchemy.orm import declarative_base\n\nBase = declarative_base()\n\n\n${models || "# no tables yet\n"}` },
    { path: "app/flows.py", content: flowsPy(d) },
    { path: "app/integrations.py", content: PY_INTEGRATIONS },
    { path: "app/main.py", content: `from fastapi import FastAPI, HTTPException\n\nfrom .flows import FLOWS\n\napp = FastAPI(title=${lit(d.name)})\n\n\n${routes}\n@app.post("/events/{name}")\ndef fire_event(name: str, payload: dict):\n    if name not in FLOWS:\n        raise HTTPException(404, "Unknown event")\n    return FLOWS[name](dict(payload))\n` },
  ];
}

function django(d: Diagram, ai: boolean): ZipFile[] {
  const models = tables(d)
    .map((t) => {
      const cols = t.fields.map((f) => {
        if (f.type === "foreign_key") return `    ${f.name} = models.ForeignKey("${pascal(str(f.target))}", on_delete=models.${str((f as { on_delete?: string }).on_delete) === "set_null" ? "SET_NULL" : str((f as { on_delete?: string }).on_delete) === "protect" ? "PROTECT" : "CASCADE"}, null=${f.required ? "False" : "True"})`;
        if (f.type === "many_to_many") return `    ${f.name} = models.ManyToManyField("${pascal(str(f.target))}", blank=True)`;
        const k = { string: "CharField(max_length=255", text: "TextField(", integer: "IntegerField(", number: "FloatField(", boolean: "BooleanField(", date: "DateField(", datetime: "DateTimeField(" }[f.type] ?? "CharField(max_length=255";
        const sep = k.endsWith("(") ? "" : ", ";
        return `    ${f.name} = models.${k}${sep}${f.required ? "" : "null=True, blank=True"})`.replace(/, \)/, ")");
      });
      return `class ${t.name}(models.Model):\n${cols.join("\n") || "    pass"}\n`;
    })
    .join("\n\n");
  return [
    { path: "README.md", content: README(d, "django", ai, "```sh\npip install django\n# add \"app\" to INSTALLED_APPS in your Django project, then\npython manage.py makemigrations app && python manage.py migrate\n```") },
    { path: "app/__init__.py", content: "" },
    { path: "app/models.py", content: `from django.db import models\n\n\n${models || "# no tables yet\n"}` },
    { path: "app/flows.py", content: flowsPy(d) },
    { path: "app/integrations.py", content: PY_INTEGRATIONS },
    { path: "app/views.py", content: `import json\n\nfrom django.http import JsonResponse\nfrom django.views.decorators.csrf import csrf_exempt\n\nfrom .flows import FLOWS\n\n\n@csrf_exempt\ndef fire_event(request, name):\n    if name not in FLOWS:\n        return JsonResponse({"detail": "Unknown event"}, status=404)\n    payload = json.loads(request.body or "{}")\n    return JsonResponse(FLOWS[name](payload))\n` },
  ];
}

function express(d: Diagram, ai: boolean): ZipFile[] {
  const schema = tables(d)
    .map((t) => {
      const cols = t.fields
        .filter((f) => f.type !== "many_to_many")
        .map((f) => `  ${f.name} ${sqlType(f.type)}${f.required ? " NOT NULL" : ""}`);
      return `CREATE TABLE ${snake(t.name)}s (\n  id SERIAL PRIMARY KEY${cols.length ? ",\n" + cols.join(",\n") : ""}\n);`;
    })
    .join("\n\n");
  const fns = events(d).map((e) => {
    const body = renderSteps(d, e.node.id, "js", 1, undefined);
    return `export async function ${e.name}(ctx) {\n${body.join("\n")}\n  return ctx;\n}\n`;
  });
  const registry = events(d).map((e) => `  ${e.name},`).join("\n");
  return [
    { path: "README.md", content: README(d, "express", ai, "```sh\nnpm install\npsql -f db/schema.sql\nnpm start\n```") },
    { path: "package.json", content: JSON.stringify({ name: slug(d.name), private: true, type: "module", scripts: { start: "node src/index.js" }, dependencies: { express: "^4.19.0" } }, null, 2) + "\n" },
    { path: "db/schema.sql", content: schema + "\n" },
    { path: "src/integrations.js", content: `// Yours to edit. Blueprint will not overwrite this file.\nexport const send_sms = async (to, msg) => console.log("[sms]", to, msg);\nexport const send_email = async (to, subject, msg) => console.log("[email]", to, subject, msg);\nexport const charge_payment = async (provider, amount) => console.log("[payment]", provider, amount);\nexport const custom_code = async (id, ctx) => console.log("[custom]", id, "not implemented yet");\nexport const run_query = async (sql) => { console.log("[sql]", sql); return []; };\n` },
    { path: "src/flows.js", content: `import * as integrations from "./integrations.js";\n\nconst render = (t, ctx) => t.replace(/\\{(\\w+)\\}/g, (_, k) => ctx[k] ?? "");\nconst compare = (a, op, b) => {\n  if (op === "contains") return String(a ?? "").toLowerCase().includes(String(b).toLowerCase());\n  if (typeof a === "number") b = Number(b);\n  const t = { eq: a === b, ne: a !== b, gt: a > b, gte: a >= b, lt: a < b, lte: a <= b };\n  return t[op] ?? false;\n};\n\n${fns.join("\n")}\nexport const FLOWS = {\n${registry}\n};\n` },
    { path: "src/index.js", content: `import express from "express";\nimport { FLOWS } from "./flows.js";\n\nconst app = express();\napp.use(express.json());\n\napp.post("/events/:name", async (req, res) => {\n  const flow = FLOWS[req.params.name];\n  if (!flow) return res.status(404).json({ detail: "Unknown event" });\n  res.json(await flow({ ...req.body }));\n});\n\napp.listen(3000, () => console.log("Listening on :3000"));\n` },
  ];
}

export function generateFiles(d: Diagram, target: string, ai: boolean): ZipFile[] {
  switch (target) {
    case "django": return django(d, ai);
    case "express": return express(d, ai);
    default: return fastapi(d, ai);
  }
}

HEADER = '"""GENERATED by Blueprint. Do not edit; change the diagram and regenerate."""\n'


def _plural(name: str) -> str:
    return snake(name) + "s"


def _node_ident(node_id: str) -> str:
    return "n_" + "".join(c if c.isalnum() else "_" for c in node_id)


def _render_steps(ir: SystemIR, flow: FlowIR, steps: list[Step], ind: int) -> list[str]:
    pad, lines = "    " * ind, []
    if not steps:
        return [pad + "pass"]
    for s in steps:
        p = s.params
        lines.append(f"{pad}# block {s.node_id}")
        if s.kind == "condition":
            lines.append(f"{pad}if runtime.compare(ctx.get({p['field']!r}), {p['operator']!r}, {p['value']!r}):")
            lines += _render_steps(ir, flow, s.then, ind + 1)
            if s.otherwise:
                lines.append(f"{pad}else:")
                lines += _render_steps(ir, flow, s.otherwise, ind + 1)
        elif s.kind == "set_field":
            lines.append(f"{pad}ctx[{p['field']!r}] = {coerce_value(ir, flow.entity, p['field'], p['value'])!r}")
        elif s.kind == "update_status":
            lines.append(f"{pad}ctx['status'] = {p['status']!r}")
        elif s.kind == "send_sms":
            lines.append(f"{pad}integrations.send_sms(ctx.get({p['to_field']!r}), runtime.render({p['message']!r}, ctx))")
        elif s.kind == "send_email":
            lines.append(f"{pad}integrations.send_email(ctx.get({p['to_field']!r}), runtime.render({p['subject']!r}, ctx), runtime.render({p['message']!r}, ctx))")
        elif s.kind == "charge_payment":
            lines.append(f"{pad}integrations.charge_payment({p['provider']!r}, ctx.get({p['amount_field']!r}), ctx)")
        elif s.kind == "sql_query":
            lines.append(f"{pad}ctx[{p['result_key']!r}] = query_runner({p['sql']!r}, ctx) if query_runner else []")
        elif s.kind == "custom_code":
            lines.append(f"{pad}ctx = {_node_ident(s.node_id)}(ctx) or ctx")
        else:
            lines.append(f"{pad}pass  # unsupported block kind {s.kind}")
    return lines


def _flows_py(ir: SystemIR) -> str:
    custom = sorted({s.node_id for f in ir.flows for s in walk_steps(f.steps) if s.kind == "custom_code"})
    out = [HEADER, "from . import integrations, runtime"]
    out += [f"from .custom.{_node_ident(n)} import run as {_node_ident(n)}" for n in custom]
    out.append("")
    for f in ir.flows:
        out += ["", f"def run_{f.event}(ctx: dict, query_runner=None) -> dict:",
                f'    """Event \'{f.event}\'' + (f" on {f.entity}" if f.entity else "") + '."""']
        out += _render_steps(ir, f, f.steps, 1)
        out.append("    return ctx")
        out.append("")
    out += ["", "FLOWS = {"] + [f"    {f.event!r}: run_{f.event}," for f in ir.flows] + ["}", ""]
    return "\n".join(out)


def _models_py(ir: SystemIR) -> str:
    out = [HEADER, "from __future__ import annotations", "import datetime as dt", "from typing import Optional", "",
           "from sqlalchemy import Boolean, Column, Date, DateTime, Float, ForeignKey, Integer, String, Table, Text",
           "from sqlalchemy.orm import Mapped, mapped_column, relationship", "", "from .db import Base", ""]
    for e in ir.entities:
        for field in e.fields:
            if field.type == "many_to_many":
                table, other = f"{_plural(e.name)}_{field.name}", _plural(field.target or "")
                out += [
                    f"{table} = Table({table!r}, Base.metadata,",
                    f"    Column({_plural(e.name) + '_id'!r}, ForeignKey({(_plural(e.name) + '.id')!r}), primary_key=True),",
                    f"    Column({other + '_id'!r}, ForeignKey({(other + '.id')!r}), primary_key=True),",
                    ")",
                ]
    for e in ir.entities:
        out += ["", f"class {e.name}(Base):", f"    __tablename__ = {_plural(e.name)!r}",
                "    id: Mapped[int] = mapped_column(primary_key=True)"]
        for f in e.fields:
            if f.type == "foreign_key":
                ann = "int" if f.required else "Optional[int]"
                target = _plural(f.target or "")
                delete = {"cascade": "CASCADE", "set_null": "SET NULL", "restrict": "RESTRICT"}.get(f.on_delete, "CASCADE")
                out.append(f"    {f.name}_id: Mapped[{ann}] = mapped_column(ForeignKey({(target + '.id')!r}, ondelete={delete!r}), nullable={not f.required})")
            elif f.type == "many_to_many":
                out.append(f"    {f.name}: Mapped[list[{f.target}]] = relationship(secondary={(_plural(e.name) + '_' + f.name)})")
            else:
                ann = PY[f.type] if f.required else f"Optional[{PY[f.type]}]"
                out.append(f"    {f.name}: Mapped[{ann}] = mapped_column({SA[f.type]}, nullable={not f.required})")
        out.append("")
    return "\n".join(out)


def _schemas_py(ir: SystemIR) -> str:
    out = [HEADER, "import datetime as dt", "from typing import Any, Optional", "",
           "from pydantic import BaseModel, ConfigDict, Field, field_serializer", ""]
    out += ["", "class EventIn(BaseModel):", "    entity_id: Optional[int] = None",
            "    payload: dict[str, Any] = Field(default_factory=dict)", ""]
    for e in ir.entities:
        out += ["", f"class {e.name}In(BaseModel):"]
        if not e.fields:
            out.append("    pass")
        for f in e.fields:
            if f.type == "foreign_key":
                key = f"{f.name}_id"
                out.append(f"    {key}: int" if f.required else f"    {key}: Optional[int] = None")
            elif f.type == "many_to_many":
                out.append(f"    {f.name}: list[int] = Field(default_factory=list)")
            else:
                out.append(f"    {f.name}: {PY[f.type]}" if f.required else f"    {f.name}: Optional[{PY[f.type]}] = None")
        out += ["", "", f"class {e.name}Out({e.name}In):", "    model_config = ConfigDict(from_attributes=True)", "    id: int", ""]
        for f in e.fields:
            if f.type == "many_to_many":
                out += [f"    @field_serializer({f.name!r})",
                        f"    def serialize_{f.name}(self, value):",
                        "        return [item.id for item in value]", ""]
    return "\n".join(out)


def _main_py(ir: SystemIR) -> str:
    out = [HEADER, "from fastapi import Depends, FastAPI, HTTPException",
           "import re", "from fastapi.encoders import jsonable_encoder", "from sqlalchemy import select, text",
           "from sqlalchemy.orm import Session", "",
           "from . import flows, models, schemas", "from .db import Base, engine, get_db", "",
           "Base.metadata.create_all(bind=engine)",
           f"app = FastAPI(title={ir.name!r})", "",
           "", '@app.get("/health")', "def health():", '    return {"status": "ok"}', ""]
    for e in ir.entities:
        n, route = e.name, "/" + _plural(e.name)
        m2m_fields = [field.name for field in e.fields if field.type == "many_to_many"]
        out += [
            "", f'@app.get("{route}", response_model=list[schemas.{n}Out])',
            f"def list_{_plural(e.name)}(db: Session = Depends(get_db)):",
            f"    return list(db.scalars(select(models.{n})))", "",
            "", f'@app.post("{route}", response_model=schemas.{n}Out, status_code=201)',
            f"def create_{snake(n)}(body: schemas.{n}In, db: Session = Depends(get_db)):",
            f"    row = models.{n}(**body.model_dump(exclude={sorted(m2m_fields)!r}))", "    db.add(row)", "    db.flush()",
        ]
        for field in e.fields:
            if field.type == "many_to_many":
                out += [
                    f"    related_ids = body.{field.name}",
                    f"    related = list(db.scalars(select(models.{field.target}).where(models.{field.target}.id.in_(related_ids)))) if related_ids else []",
                    f"    if len(related) != len(set(related_ids)): raise HTTPException(422, 'Invalid {field.name} id')",
                    f"    row.{field.name} = related",
                ]
        out += [
            "    db.commit()", "    db.refresh(row)",
            "    return row", "",
            "", f'@app.get("{route}/{{item_id}}", response_model=schemas.{n}Out)',
            f"def get_{snake(n)}(item_id: int, db: Session = Depends(get_db)):",
            f"    row = db.get(models.{n}, item_id)",
            "    if row is None:", '        raise HTTPException(404, "Not found")', "    return row", "",
            "", f'@app.put("{route}/{{item_id}}", response_model=schemas.{n}Out)',
            f"def update_{snake(n)}(item_id: int, body: schemas.{n}In, db: Session = Depends(get_db)):",
            f"    row = db.get(models.{n}, item_id)",
            "    if row is None:", '        raise HTTPException(404, "Not found")',
            f"    for k, v in body.model_dump(exclude={sorted(m2m_fields)!r}).items():", "        setattr(row, k, v)",
        ]
        for field in e.fields:
            if field.type == "many_to_many":
                out += [
                    f"    related_ids = body.{field.name}",
                    f"    related = list(db.scalars(select(models.{field.target}).where(models.{field.target}.id.in_(related_ids)))) if related_ids else []",
                    f"    if len(related) != len(set(related_ids)): raise HTTPException(422, 'Invalid {field.name} id')",
                    f"    row.{field.name} = related",
                ]
        out += [
            "    db.commit()", "    db.refresh(row)", "    return row", "",
            "", f'@app.delete("{route}/{{item_id}}", status_code=204)',
            f"def delete_{snake(n)}(item_id: int, db: Session = Depends(get_db)):",
            f"    row = db.get(models.{n}, item_id)",
            "    if row is None:", '        raise HTTPException(404, "Not found")',
            "    db.delete(row)", "    db.commit()", "",
        ]
    out += ["", "EVENT_ENTITIES = {"]
    out += [f"    {f.event!r}: " + (f"models.{f.entity}," if f.entity else "None,") for f in ir.flows]
    out += ["}", "", "",
            '@app.post("/events/{event_name}")',
            "def trigger_event(event_name: str, body: schemas.EventIn, db: Session = Depends(get_db)):",
            "    flow = flows.FLOWS.get(event_name)",
            "    if flow is None:", '        raise HTTPException(404, f"Unknown event {event_name!r}")',
            "    model = EVENT_ENTITIES.get(event_name)",
            "    row, ctx = None, dict(body.payload)",
            "    if model is not None:",
            "        if body.entity_id is None:", '            raise HTTPException(422, "entity_id is required for this event")',
            "        row = db.get(model, body.entity_id)",
            "        if row is None:", '            raise HTTPException(404, "Record not found")',
            "        ctx = {**{c.name: getattr(row, c.name) for c in row.__table__.columns}, **body.payload}",
            "    before = dict(ctx)",
            "    def query_runner(sql, values):",
            "        names = re.findall(r'(?<!:):([A-Za-z_][A-Za-z0-9_]*)', sql)",
            "        params = {name: values[name] for name in names}",
            "        return [dict(row) for row in db.execute(text(sql), params).mappings().all()]",
            "    result = flow(ctx, query_runner)",
            "    if row is not None:",
            "        for col in row.__table__.columns.keys():",
            '            if col != "id" and col in result and result[col] != before.get(col):',
            "                setattr(row, col, result[col])",
            "        db.commit()",
            '    return {"event": event_name, "context": jsonable_encoder(result)}', ""]
    return "\n".join(out)


def _tests_py(ir: SystemIR) -> str:
    out = [HEADER, "import os", "import tempfile", "",
           "os.environ['DATABASE_URL'] = 'sqlite:///' + os.path.join(tempfile.mkdtemp(), 'test.db')", "",
           "from fastapi.testclient import TestClient  # noqa: E402", "from app.main import app  # noqa: E402", "",
           "client = TestClient(app)", "",
           "", "def test_health():", "    assert client.get('/health').json() == {'status': 'ok'}", ""]
    for f in ir.flows:
        out += ["", f"def test_event_{f.event}():"]
        if f.entity:
            ent = ir.entity(f.entity)
            body = {x.name: SAMPLE[x.type] for x in ent.fields if x.type in SAMPLE and (x.name != "status" or x.required)}
            out += [f"    created = client.post('/{_plural(f.entity)}', json={body!r})",
                    "    assert created.status_code == 201, created.text",
                    f"    r = client.post('/events/{f.event}', json={{'entity_id': created.json()['id'], 'payload': {{}}}})"]
        else:
            out += [f"    r = client.post('/events/{f.event}', json={{'payload': {{}}}})"]
        out.append("    assert r.status_code == 200, r.text")
        top = [s for s in f.steps if s.kind == "update_status"]
        if f.entity and top:
            out += [f"    fetched = client.get(f'/{_plural(f.entity)}/{{created.json()[\"id\"]}}')",
                    f"    assert fetched.json()['status'] == {top[-1].params['status']!r}"]
        out.append("")
    return "\n".join(out)


